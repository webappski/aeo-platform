test('report --white-label (HTML + MD) produces zero fingerprint AND zero advisory matches, drops bridge + actions, keeps a neutral title', async () => {
  await withTmpProject('aeo-e2e-wl-clean-', async (dir) => {
    seedSummary(dir);
    const today = todayDateString();
    const title = 'AEO Visibility Snapshot — testbrand.com';
    const r = spawnCli(
      ['report', '--no-open', '--white-label', '--report-title', title],
      { cwd: dir, env: KEYS },
    );
    assertExitCode(r, 0, 'report --white-label should exit 0');
    const html = readFileSync(join(reportsDateDir(dir, DOMAIN, today), 'report.html'), 'utf-8');
    const md = readFileSync(join(reportsDateDir(dir, DOMAIN, today), 'report.md'), 'utf-8');

    // (1) Fingerprint denylist — ZERO matches in BOTH files.
    for (const re of FINGERPRINT_DENYLIST) {
      assert.doesNotMatch(html, re, `white-label HTML must not match fingerprint ${re}`);
      assert.doesNotMatch(md, re, `white-label MD must not match fingerprint ${re}`);
    }

    // (2) Advisory / outreach denylist — ZERO matches in BOTH files. THIS is the
    // class the gate-1 test missed (HTML-only + no outreach tokens).
    for (const re of ADVISORY_DENYLIST) {
      assert.doesNotMatch(html, re, `white-label HTML must not match advisory ${re}`);
      assert.doesNotMatch(md, re, `white-label MD must not match advisory ${re}`);
    }

    // (3) MC bridge + Actions + outreach drafts gone (HTML).
    assert.doesNotMatch(html, /<article[^>]*\bid="mc-bridge"/, 'white-label must drop the MC bridge anchor');
    assert.doesNotMatch(html, /Recommended actions/, 'white-label must drop the Actions / recommendation block');
    assert.doesNotMatch(html, /Outreach drafts/, 'white-label must not render outreach drafts');
    assert.doesNotMatch(html, /Webappski plan/, 'white-label must not render the Webappski commerce fork');

    // (4) Neutral, parameterizable title + honest methodology footer present (both).
    assert.match(html, /<title>AEO Visibility Snapshot — testbrand\.com<\/title>/, 'white-label must use the neutral --report-title');
    assert.match(html, /Methodology: \d+ buyer-intent quer/, 'white-label HTML must carry the honest methodology footer');
    assert.match(html, /no confidence intervals are implied/, 'HTML methodology must disclaim statistics it does not have');
    assert.match(md, /Methodology: \d+ buyer-intent quer/, 'white-label MD must carry the honest methodology footer');
    assert.match(md, /no confidence intervals are implied/, 'MD methodology must disclaim statistics it does not have');

    // (5) The statistics survive — this is still a real report (both files).
    assert.match(html, /Unified Visibility Index/i, 'white-label HTML must keep the score/UVI');
    assert.match(html, /RivalCo/, 'white-label HTML must keep the competitors table');
    assert.match(md, /Competitors vs you/, 'white-label MD must keep the competitors section');
    assert.match(md, /RivalCo/, 'white-label MD must keep the competitor barchart');
    // The neutralised citation sections keep their statistics, just no advice.
    assert.match(md, /Domain Share of Voice/i, 'white-label MD must keep the domain share-of-voice table');
    assert.match(md, /Citation Sources/, 'white-label MD must keep the (renamed) citation-sources table');
    assert.match(md, /g2\.com/, 'white-label MD must keep the cited domains');
  });
});

