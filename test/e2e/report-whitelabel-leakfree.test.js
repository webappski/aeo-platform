// ────────────────────────────────────────────────────────────────────────────
// AP-REPORT-ANSWER-REVEAL — click-to-reveal verbatim engine answers behind each
// query×engine matrix cell, in BOTH default and white-label HTML.
//
// The full answer is MEASURED DATA, not tool/agency copy. It is shown in both
// modes. So the leak surface inside a reveal is NOT advisory words ("recommend /
// best / fastest" are the engine's own words on real CDN-style answers) — it is
// the tool/agency IDENTITY fingerprint (aeo-platform / webappski / mc-bridge),
// which must be 0 in white-label INCLUDING the embedded answer text. The
// reveal-specific tests below scan the embedded answers explicitly for the
// IDENTITY subset, while keeping the full advisory ban on the generated chrome
// (covered by the white-label tests above, whose seed has no raw files so the
// reveal falls back to clean excerpts).
//
// Mutation-sanity (run by hand to confirm teeth) — each MUST go RED:
//   - bin/aeo-tracker.js rawResponses loader: revert the model-suffixed name
//     resolution to the bare `q${qi}-${r.provider}.json` → the suffixed raw
//     files no longer load → reveal falls back to the excerpt → the "full text
//     present" assertion (longer than the excerpt, exact closing sentence) RED.
//   - html.js reveal: drop the `esc(fullText)` escape (emit raw) → the seeded
//     `<script>`/`<b>` payload renders live → the "answer is HTML-escaped" RED.
//   - html.js reveal: remove the `responseExcerpt` fallback branch → the
//     no-raw-file cell stops revealing → the fallback test RED.

// IDENTITY-only fingerprints — these must be 0 even inside embedded answers.
// (A real engine answer about CDNs never says "aeo-platform" / "webappski".)
const IDENTITY_FINGERPRINT = [
  /aeo-platform/i,
  /@webappski/i,
  /webappski/i,
  /mission ?control/i,
  /mc-bridge/i,
];

// A "named" cell needs a query+provider with mention:'yes' and a matching raw
// JSON file named `q{N}-{provider}-{sanitizedModel}.json` (the name the run
// writer produces — and the name the fixed report loader resolves).
function seedRevealProject(dir, { fullText, withRawFile = true } = {}) {
  const today = todayDateString();
  const dd = responsesDateDir(dir, DOMAIN, today);
  mkdirSync(dd, { recursive: true });
  // The full answer the reveal must surface verbatim. CLEAN of advisory words
  // (so the white-label advisory ban still holds) but carries a unique closing
  // sentence + an HTML-injection payload to prove (a) full text — not excerpt —
  // and (b) escaping.
  const answer = fullText || (
    'TestBrand operates a global network with strong price-to-performance. '
    + 'It appears across several category comparisons this period. '
    + 'A <script>alert(1)</script> token and an ampersand & angle < bracket are '
    + 'embedded to verify HTML escaping. '
    + 'UNIQUE_CLOSING_SENTENCE_THAT_NO_EXCERPT_WOULD_CONTAIN_END.'
  );
  const summary = {
    date: today,
    brand: 'TestBrand',
    domain: 'testbrand.com',
    score: 50,
    mentions: 1,
    total: 1,
    topCompetitors: [{ name: 'RivalCo', count: 2 }],
    results: [
      {
        query: 'Q1', queryText: 'best test brands 2026', provider: 'openai', label: 'ChatGPT',
        model: 'gpt-5-search-api', mode: 'web', mention: 'yes', position: 1, citationCount: 1,
        canonicalCitations: ['https://testbrand.com/page'], competitors: ['RivalCo'], competitorsUnverified: [],
        responseQuality: 'ok', hasBrandInCitations: true,
        // A SHORT excerpt — distinct from the full answer so the "full not
        // excerpt" assertion has teeth (the excerpt lacks the unique sentence).
        responseExcerpt: 'TestBrand operates a global network with strong price-to-performance.',
        elapsedMs: 100, inputTokens: 10, outputTokens: 10, costUsd: 0.5,
      },
    ],
  };
  writeFileSync(join(dd, '_summary.json'), JSON.stringify(summary));
  if (withRawFile) {
    // Model-suffixed name the writer produces — the fixed loader must resolve it.
    writeFileSync(
      join(dd, 'q1-openai-gpt-5-search-api.json'),
      JSON.stringify({ choices: [{ message: { content: answer } }] }),
    );
  }
  return { today, answer };
}

test('reveal: default HTML carries a per-cell <details> with the FULL, HTML-escaped verbatim answer', async () => {
  await withTmpProject('aeo-e2e-reveal-default-', async (dir) => {
    const { today } = seedRevealProject(dir);
    const r = spawnCli(['report', '--no-open'], { cwd: dir, env: KEYS });
    assertExitCode(r, 0, 'report should exit 0');
    const html = readFileSync(join(reportsDateDir(dir, DOMAIN, today), 'report.html'), 'utf-8');

    // (a) the reveal accordion exists with a non-empty answer body.
    assert.match(html, /<details class="reveal">/, 'default HTML must render the reveal <details>');
    assert.match(html, /<span class="reveal-q">best test brands 2026<\/span>/, 'reveal summary must be headed by the query text itself, not a Q-index');
    assert.match(html, /<div class="reveal-excerpt">[^<]/, 'reveal body must be non-empty');

    // FULL answer, not the truncated excerpt — the unique closing sentence is in
    // the full answer only, and the cell is NOT tagged "excerpt".
    assert.match(html, /UNIQUE_CLOSING_SENTENCE_THAT_NO_EXCERPT_WOULD_CONTAIN_END\./, 'reveal must carry the FULL answer (unique sentence present)');
    const revealBlock = html.slice(html.indexOf('<details class="reveal">'));
    assert.doesNotMatch(revealBlock.split('</details>')[0], /reveal-trunc/, 'a cell WITH a raw file must NOT be tagged as an excerpt fallback');

    // (b) the answer is HTML-ESCAPED — the injection payload is inert text, the
    // live page has no <script>alert / unescaped tag from the answer.
    assert.match(html, /&lt;script&gt;alert\(1\)&lt;\/script&gt;/, 'injected <script> must be HTML-escaped');
    assert.doesNotMatch(html, /<script>alert\(1\)<\/script>/, 'the answer must NOT inject a live <script>');

    // print-open JS present so Save-as-PDF expands every reveal.
    assert.match(html, /addEventListener\('beforeprint'/, 'print-open listener must be wired');
  });
});

test('reveal: white-label HTML embeds the FULL answer and is IDENTITY-fingerprint-free INCLUDING the embedded answer text', async () => {
  await withTmpProject('aeo-e2e-reveal-wl-', async (dir) => {
    const { today } = seedRevealProject(dir);
    const r = spawnCli(['report', '--no-open', '--white-label'], { cwd: dir, env: KEYS });
    assertExitCode(r, 0, 'report --white-label should exit 0');
    const html = readFileSync(join(reportsDateDir(dir, DOMAIN, today), 'report.html'), 'utf-8');

    // The reveal renders in white-label too (the answer is measured data).
    assert.match(html, /<details class="reveal">/, 'white-label HTML must still render the reveal <details>');
    assert.match(html, /UNIQUE_CLOSING_SENTENCE_THAT_NO_EXCERPT_WOULD_CONTAIN_END\./, 'white-label reveal must carry the full answer');

    // The WHOLE file — chrome AND embedded answers — is free of the tool/agency
    // IDENTITY fingerprint. This is the load-bearing white-label leak claim for
    // the reveal: the embedded answer text adds no identity tell.
    for (const re of IDENTITY_FINGERPRINT) {
      assert.doesNotMatch(html, re, `white-label HTML (incl. embedded answers) must not match identity ${re}`);
    }
    // The embedded answer region specifically — scan just the reveal bodies.
    const bodies = [...html.matchAll(/<div class="reveal-excerpt">([\s\S]*?)<\/div>/g)].map(m => m[1]);
    assert.ok(bodies.length > 0, 'white-label must have at least one embedded answer');
    for (const body of bodies) {
      for (const re of IDENTITY_FINGERPRINT) {
        assert.doesNotMatch(body, re, `embedded answer must not match identity ${re}`);
      }
    }
  });
});

