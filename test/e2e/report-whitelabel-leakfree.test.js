/**
 * E2E — `report --white-label` is a STATISTICS-ONLY, fingerprint- AND
 * recommendation-free client snapshot, leak-free BY CONSTRUCTION (no manual
 * scrub). The deliverable ships under the legend of a self-made local stats
 * tool, so ANY consulting / outreach / advisory verb in the RENDERED output
 * (HTML *and* MARKDOWN) breaks the legend exactly like a tool fingerprint does.
 *
 * White-label is a SUPERSET of --public. On top of suppressing the cost card +
 * source-path footnotes, it must additionally remove, from BOTH served files:
 *
 *   (1) every tool/agency fingerprint — the «aeo-platform» masthead mark,
 *       version, colophon wordmark, repo "open source" link, «Generated by …»;
 *   (2) the entire Webappski / Mission-Control bridge (<article id="mc-bridge">
 *       + the "Webappski plan" fork + commerce CTA);
 *   (3) the recommendation / outreach CLASS — every advisory verb that renders:
 *       «Pitch the top 3», «Outreach move», «Where to get mentioned»,
 *       «guest post», «concentrate outreach», «push for inclusion»,
 *       «pitch … first to convert», «closing the gap», «defend it», etc. This
 *       spans the three citation sections (Domain SOV / Categories / Canonical
 *       Sources), the Competitors subheading, the hero narrative, and the
 *       HTML-only hero "Lift opportunities" KPI + the listicle "Top gap" cell.
 *       The dead `.outreach-*` CSS rules are stripped too (inert, but they are
 *       literal «outreach» text a whole-file scrub would flag).
 *
 * It must KEEP the statistics in the same layout, under a neutral, parameterizable
 * title, with an honest methodology footer.
 *
 * The denylist below is a REGRESSION TRIPWIRE, not the class boundary. The class
 * is "advisory copy that renders in white-label" and is closed at-source in
 * lib/report/{sections,html,markdown}.js (gated on whiteLabel). The seed is built
 * to FORCE the advisory branches to render in the DEFAULT report (concentrated
 * single-category listicle pool, top-3 ≥60% share, named>0 AND src>0,
 * topCanonicalSources present, citationClassification absent) — so the two-sided
 * assertions and the per-gate mutation check below have real teeth instead of
 * false-passing because the branch never fired.
 *
 * The test is TWO-SIDED on purpose: each denylist token is asserted PRESENT in
 * the default report AND ABSENT in --white-label, for HTML and MD alike. A
 * one-sided "absent" test false-passes if --white-label silently stops being
 * wired (the surface would be absent in both because the seed never produced it),
 * or if a broken signature strips the copy from the DEFAULT report too.
 *
 * Mutation-sanity (run by hand to confirm teeth) — each MUST go RED. Verified
 * 2026-06-18 by pulling each gate, `node --test`, observing RED, restoring:
 *   - sections.js sectionDomainShareOfVoice: drop the `opts.whiteLabel ? … : …`
 *     sub → «Pitching the top 3 … Outreach templates» returns to white-label MD.
 *   - sections.js sectionDomainCategories: drop the whiteLabel column-gate →
 *     «Outreach move» column + per-row playbook returns.
 *   - sections.js sectionCanonicalSources: drop the whiteLabel branch →
 *     «Where to get mentioned» + «guest post» + «fastest path» return.
 *   - sections.js sectionCompetitors: drop the whiteLabel sub → «invest …
 *     closing the gap» returns.
 *   - html.js narrativeFor: drop the `if (whiteLabel)` block → «push for
 *     first-position / pitch … to convert» returns to the hero narrative.
 *   - html.js: change `if (!whiteLabel)` back to unconditional on the Lift KPI →
 *     «Pitch those publishers / to convert» returns.
 *   - html.js: change `if (!whiteLabel && top4Domains.length>0)` back to drop the
 *     whiteLabel guard → «push for inclusion / outreach is the lift» returns.
 *   - html.js domainTitle/categorySub: drop the `if (whiteLabel)` block → «Pitch
 *     the top 3 first» / «concentrate outreach» / «lift compounds» return.
 *   - html.js CSS strip: drop the `.outreach-*` strip → «.outreach-…» dead CSS
 *     returns to the white-label <style>.
 *   - sections.js sectionRunVerdict: drop the `whiteLabel ? stat : stat+advisory`
 *     branch on the lift note → «the shortest lift on this report …» returns to
 *     the white-label MD run verdict (verified RED 2026-08-26).
 *
 * Pure file-write + subprocess; no network, no live API.
 */
